// Generate REAL projected US state geometry for the Sigma Motors regional map
// plugin. Uses actual TIGER-derived geodata (us-atlas states-10m) and a real
// d3-geo albersUsa projection (which also insets Alaska + Hawaii), instead of
// hand-authored polygon points.
//
// Emits a single JS file the plugin can inline: per-state projected path +
// region assignment, per-region merged outline + centroid, and the national
// outline (for the drop shadow / outer coastline stroke).
const fs = require('fs');
const path = require('path');
const { geoAlbersUsa, geoPath } = require('d3-geo');
const topojson = require('topojson-client');

const W = 960, H = 600, PAD = 12;

const ATLAS = path.join(__dirname, 'node_modules', 'us-atlas');
const statesTopo = JSON.parse(fs.readFileSync(path.join(ATLAS, 'states-10m.json')));
const nationTopo = JSON.parse(fs.readFileSync(path.join(ATLAS, 'nation-10m.json')));

const statesFC = topojson.feature(statesTopo, statesTopo.objects.states);
const nationFC = topojson.feature(nationTopo, nationTopo.objects.nation);

// Fit the projection to the full state set so nothing (incl. the AK/HI insets)
// is clipped, then reuse that exact same projection for every derived path so
// state / region / nation outlines all register perfectly.
const projection = geoAlbersUsa().fitExtent([[PAD, PAD], [W - PAD, H - PAD]], statesFC);
const pathGen = geoPath(projection);

// Round to 1 decimal -- d3 emits ~15 significant digits, which triples the
// payload for sub-pixel precision nobody can see at dashboard scale.
const round = (d) => d.replace(/-?\d+\.\d+/g, (m) => String(Math.round(parseFloat(m) * 10) / 10));

const REGION_OF = {};
const REGIONS = {
  West: ['Washington', 'Oregon', 'California', 'Nevada', 'Idaho', 'Montana', 'Wyoming', 'Utah', 'Colorado', 'Alaska', 'Hawaii'],
  Southwest: ['Arizona', 'New Mexico', 'Texas', 'Oklahoma'],
  Midwest: ['North Dakota', 'South Dakota', 'Nebraska', 'Kansas', 'Minnesota', 'Iowa', 'Missouri', 'Wisconsin', 'Illinois', 'Michigan', 'Indiana', 'Ohio'],
  South: ['Arkansas', 'Louisiana', 'Mississippi', 'Alabama', 'Tennessee', 'Kentucky', 'Georgia', 'Florida', 'South Carolina', 'North Carolina', 'Virginia', 'West Virginia'],
  Northeast: ['Maryland', 'Delaware', 'New Jersey', 'Pennsylvania', 'New York', 'Connecticut', 'Rhode Island', 'Massachusetts', 'Vermont', 'New Hampshire', 'Maine', 'District of Columbia'],
};
for (const [region, names] of Object.entries(REGIONS)) {
  names.forEach((n) => { REGION_OF[n] = region; });
}

const states = [];
const unassigned = [];
for (const f of statesFC.features) {
  const name = f.properties.name;
  const d = pathGen(f);
  // geoAlbersUsa returns null outside its composite domain (e.g. Puerto Rico),
  // which yields an empty path -- skip rather than emit a broken entry.
  if (!d) continue;
  const region = REGION_OF[name];
  if (!region) { unassigned.push(name); continue; }
  states.push({ n: name, r: region, d: round(d) });
}

// Merge each region's state geometries only to derive a TRUE region centroid
// for marker placement (averaging per-state centroids instead would bias
// toward whichever side of a region has more small states). The region's
// visible border comes from the mesh below, not from this merged outline.
const geomByName = new Map();
statesTopo.objects.states.geometries.forEach((g) => geomByName.set(g.properties.name, g));

const regions = {};
for (const [region, names] of Object.entries(REGIONS)) {
  const geoms = names.map((n) => geomByName.get(n)).filter(Boolean);
  const merged = topojson.merge(statesTopo, geoms);
  const c = pathGen.centroid(merged);
  regions[region] = { c: [Math.round(c[0] * 10) / 10, Math.round(c[1] * 10) / 10] };
}

// Borders as topojson MESHES, not per-state strokes: a mesh emits each shared
// edge exactly once, so adjacent states don't double-stroke their common
// border (which renders visibly heavier/darker than the outer edges and is
// the usual giveaway of a naively-drawn choropleth).
const sameRegion = (a, b) => REGION_OF[a.properties.name] === REGION_OF[b.properties.name];
const stateBorders = round(pathGen(
  topojson.mesh(statesTopo, statesTopo.objects.states, (a, b) => a !== b && sameRegion(a, b))
));
const regionBorders = round(pathGen(
  topojson.mesh(statesTopo, statesTopo.objects.states, (a, b) => a !== b && !sameRegion(a, b))
));

const nation = round(pathGen(nationFC));

const out =
  '// AUTO-GENERATED by scratchpad/usmapgen/gen.js -- do not hand-edit.\n' +
  '// Real us-atlas (TIGER) state geometry, d3-geo albersUsa projection,\n' +
  '// pre-projected into a ' + W + 'x' + H + ' viewBox (Alaska + Hawaii inset).\n' +
  'var US_MAP = ' + JSON.stringify({ w: W, h: H, nation, states, regions, stateBorders, regionBorders }) + ';\n';

fs.writeFileSync(path.join(__dirname, 'us-map-data.js'), out);

console.log('states emitted:', states.length);
console.log('unassigned (skipped):', unassigned.length ? unassigned.join(', ') : '(none)');
console.log('region centroids:');
for (const [r, v] of Object.entries(regions)) console.log('  ', r, v.c);
console.log('output bytes:', out.length);
